-- Apply once to the Neon database before deploying the Postgres adapter.
-- Safe to re-run; existing article rows and IDs are preserved.
CREATE TABLE IF NOT EXISTS articles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    link TEXT NOT NULL UNIQUE,
    source TEXT,
    published TEXT,
    published_ts BIGINT DEFAULT 0,
    summary TEXT,
    category TEXT DEFAULT 'general',
    image TEXT,
    fetched_at TEXT
);
CREATE INDEX IF NOT EXISTS articles_published_ts_idx
    ON articles (published_ts DESC, id DESC);
